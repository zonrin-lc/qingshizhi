function Start()
    local ok, err = pcall(function()
        local scene = Scene()
        local node = scene:CreateChild("P")
        local src = node:CreateComponent("SoundSource")
        print("[probe] declick default = " .. tostring(src:GetDeclickEnabled()))
        src:SetDeclickEnabled(false)
        print("[probe] after disable   = " .. tostring(src:GetDeclickEnabled()))
        local s = cache:GetResource("Sound", "audio/voice/lisi_c0_0-1_s1.ogg")
        print("[probe] sound loaded = " .. tostring(s ~= nil))
        src:Play(s)
        print("[probe] playing = " .. tostring(src:IsPlaying()))
    end)
    if not ok then log:Write(LOG_ERROR, "[probe] " .. tostring(err)) end
    engine:Exit()
end
